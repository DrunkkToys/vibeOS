type FlowSeverity = "warn" | "hint" | "flag"

type FlowRule = {
  id: string
  trigger: string
  pattern: string
  severity: FlowSeverity
  description?: string
}

type FlowHit = FlowRule & {
  filePath?: string
  deduped: boolean
}

type CheckFlowRulesInput = {
  tool: string
  filePath?: string
  content?: string
}

type RecordFlowWarnInput = {
  id: string
  severity: FlowSeverity
  filePath?: string
  description?: string
}

type FlowTodoInput = {
  filePath?: string
  content: string
}

function safeJsonParse(raw: string): any {
  try {
    return JSON.parse(raw)
  } catch {}
  let cleaned = raw.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '').replace(/,\s*([}\]])/g, '$1')
  return JSON.parse(cleaned)
}

