const GUARD_README_TEMPLATE = (name: string, techStack: string[]): string => {
  const stackLine = techStack.length > 0 ? techStack.map((t) => `\`${t}\``).join(", ") : "(auto-detected on next session)"
  return [
    `# ${name}`,
    "",
    "## Tech Stack",
    "",
    stackLine,
    "",
    "## Features",
    "",
    "(Feature list maintained by vibeOS — run `trinity guard` to refresh)",
    "",
    "## Getting Started",
    "",
    "```bash",
    "# Clone and install dependencies",
    "```",
    "",
  ].join("\n")
}

export function ensureProjectDocs(dir: string, techStack?: string[]): { created: string[]; skipped: string[] } {
  const created: string[] = []
  const skipped: string[] = []
  const agentsPath = join(dir, "AGENTS.md")
  const readmePath = join(dir, "README.md")

  try {
    if (!existsSync(agentsPath)) {
      try {
        writeFileSync(agentsPath, GUARD_AGENTS_TEMPLATE, "utf-8")
        created.push("AGENTS.md")
        console.error("[vibeOS] Project Guard: created AGENTS.md")
      } catch (err) {
        console.error(`[vibeOS] Project Guard: failed to create AGENTS.md: ${(err as Error).message}`)
      }
    } else {
      skipped.push("AGENTS.md")
    }
  } catch {}

  try {
    if (!existsSync(readmePath)) {
      const name = dir ? dir.split("/").pop() || "Project" : "Project"
      const stack = techStack || []
      const content = GUARD_README_TEMPLATE(name, stack)
      try {
        writeFileSync(readmePath, content, "utf-8")
        created.push("README.md")
        console.error("[vibeOS] Project Guard: created README.md")
      } catch (err) {
        console.error(`[vibeOS] Project Guard: failed to create README.md: ${(err as Error).message}`)
      }
    } else {
      skipped.push("README.md")
    }
  } catch {}

  return { created, skipped }
}
const STATE_FILE = join(homedir(), ".claude/delegation-state.json")
const FLOW_TODO_FILE = join(homedir(), ".claude/flow-todo-queue.jsonl")
const FLOW_DEDUP_FILE = join(homedir(), ".claude/.flow-dedup-keys.json")
const MAX_FLOW_TODOS = 200

const _flowWarnsSeen = new Set<string>()
let _stateWriter: ((state: any) => void) | null = null

export function setFlowStateWriter(writer: ((state: any) => void) | null): void {
  _stateWriter = typeof writer === "function" ? writer : null
}

// Persist flow dedup keys across restarts to avoid re-warnings
function loadFlowDedupKeys(): void {
  try {
    if (existsSync(FLOW_DEDUP_FILE)) {
      const raw = readFileSync(FLOW_DEDUP_FILE, "utf-8")
      const keys: string[] = safeJsonParse(raw)
      if (Array.isArray(keys)) {
        for (const k of keys) _flowWarnsSeen.add(k)
      }
    }
  } catch {}
}

function persistFlowDedupKey(key: string): void {
  try {
    mkdirSync(dirname(FLOW_DEDUP_FILE), { recursive: true })
    let keys: string[] = []
    if (existsSync(FLOW_DEDUP_FILE)) {
      try { keys = safeJsonParse(readFileSync(FLOW_DEDUP_FILE, "utf-8")) } catch {}
      if (!Array.isArray(keys)) keys = []
    }
    if (!keys.includes(key)) {
      keys.push(key)
      if (keys.length > 1000) keys = keys.slice(-500)
      writeFileSync(FLOW_DEDUP_FILE, JSON.stringify(keys), "utf-8")
    }
  } catch {}
}

