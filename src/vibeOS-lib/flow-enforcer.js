function safeJsonParse(raw) {
    if (raw == null || raw === "")
        return null;
    try {
        return JSON.parse(raw);
    }
    catch { }
    let cleaned = raw.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "").replace(/,\s*([}\]])/g, "$1");
    try {
        return JSON.parse(cleaned);
    }
    catch {
        return null;
    }
}
